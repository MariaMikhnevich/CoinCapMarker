import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const envExamplePath = join(rootDir, '.env.example');
const dotenvPath = join(rootDir, '.env');
const generatedPath = join(rootDir, 'src', 'environments', 'env.generated.ts');

/**
 * Minimal `.env` parser: `KEY=value` per line, `#` comments allowed,
 * surrounding quotes on values are stripped. Enough for flat secrets.
 */
function parseDotenv(text) {
    const values = {};
    for (const line of text.split(/\r?\n/)) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#')) continue;
        const eq = trimmed.indexOf('=');
        if (eq === -1) continue;
        const key = trimmed.slice(0, eq).trim();
        const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
        values[key] = value;
    }
    return values;
}

// Expected names come from the committed .env.example so that a typo in .env
// cannot silently produce a variable nothing reads.
const expectedKeys = Object.keys(parseDotenv(readFileSync(envExamplePath, 'utf8')));

// Environment variables win (CI passes secrets this way); local .env is the fallback.
const dotenvValues = existsSync(dotenvPath) ? parseDotenv(readFileSync(dotenvPath, 'utf8')) : {};
const entries = expectedKeys.map((key) => [key, process.env[key] ?? dotenvValues[key] ?? '']);

const escape = (value) => value.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const lines = entries.map(([key, value]) => `    ${key}: '${escape(value)}',`).join('\n');

const content = `// AUTO-GENERATED by scripts/generate-env.mjs — do not edit, never commit.
// Values come from environment variables (CI) or the local .env file.
export const env = {
${lines}
} as const;
`;

writeFileSync(generatedPath, content);

const missing = entries.filter(([, value]) => !value).map(([key]) => key);
if (missing.length > 0) {
    console.warn(`[generate-env] no values for: ${missing.join(', ')} (create .env from .env.example)`);
}
